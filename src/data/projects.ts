import type { EvidenceSource, Project, ProjectMediaState } from './types'

const privateRepo = (project: string, repository: string, path: string, type: EvidenceSource['type'], note?: string): EvidenceSource => ({
  project,
  repository,
  path,
  type,
  access: 'private',
  note,
})

const localEvidence = (project: string, path: string, type: EvidenceSource['type'], note?: string): EvidenceSource => ({
  project,
  repository: 'local working tree',
  path,
  type,
  access: 'local',
  note,
})

const ownerEvidence = (project: string, note: string): EvidenceSource => ({
  project,
  type: 'owner-confirmed',
  access: 'local',
  note,
})

const media = (
  id: string,
  label: string,
  eyebrow: string,
  description: string,
  emphasis: string[],
  palette: ProjectMediaState['palette'] = ['#070b16', '#d9b56e', '#f2ead8'],
  asset: Partial<Pick<ProjectMediaState, 'src' | 'alt' | 'sourceType' | 'fit' | 'position' | 'aspectRatio'>> = {},
): ProjectMediaState => ({
  id,
  label,
  eyebrow,
  description,
  emphasis,
  palette,
  alt: asset.alt ?? description,
  sourceType: asset.sourceType ?? 'generated',
  fit: asset.fit ?? (asset.sourceType === 'live-capture' ? 'cover' : 'contain'),
  position: asset.position ?? 'center center',
  aspectRatio: asset.aspectRatio ?? '16 / 9',
  ...(asset.src ? { src: asset.src } : {}),
})

